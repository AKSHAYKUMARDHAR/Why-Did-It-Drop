"""Is a gap between versions real, and is a gate failure certain? A report for one logged run.

    python -m eval.compare --split holdout    # reads eval/results/holdout_<model>.json, writes holdout_<model>_comparison.md
    python -m eval.compare --split dev

It reads the logged results file, the record of the run, and sends no requests. run_eval also writes this report
after every run.

Why paired: every version answers the same cases from the same evidence pack, so case difficulty is shared (a hard
case is hard for every version) and only the cases where two versions disagree say which is better. Why intervals:
on 40 cases, one answer moves a rate by 2.5 points, so a gate miss can be noise. Scoring is code (eval/score.py)
against each case's known answer; no model judges a model.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from eval.score import GATE  # noqa: E402
from eval.stats import against_gate, paired, wilson, wins_needed  # noqa: E402

NAMES = {"baseline": "Rules only (no model)", "model": "Model only", "checked": "Model + checks (ships)"}
TYPES = ["Planted, clear", "Planted, unseen type", "Planted, too small", "Natural tracking failure", "Quiet week",
         "Broad week"]


def case_type(row: dict, dev_types: set) -> str:
    kind = row["kind"]
    if kind == "planted":
        if row.get("label") == "too_small":
            return "Planted, too small"
        if (row.get("incident") or {}).get("type") not in dev_types:
            return "Planted, unseen type"
        return "Planted, clear"
    return {"natural": "Natural tracking failure", "quiet": "Quiet week", "broad": "Broad week"}.get(kind, kind)


def _rate(k: int, n: int) -> str:
    if not n:
        return "-"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {k / n:.0%} ({lo:.0%}-{hi:.0%})"


def gate_rows(rows: list[dict], v: str) -> list[tuple[str, int, int, float, str]]:
    """(criterion, k, n, limit, side) for the three rate criteria, with the same denominators as summarise()."""
    inc = [r for r in rows if r["label"] in ("clear", "too_small")]
    quiet = [r for r in rows if r["label"] in ("quiet", "broad")]
    out = lambda rs, o: sum(r["answers"][v]["outcome"] == o for r in rs)  # noqa: E731
    return [("Wrong causes", out(rows, "wrong"), len(rows), GATE["wrong_rate"], "max"),
            ("Right on incidents", out(inc, "right"), len(inc), GATE["right_rate_incidents"], "min"),
            ("False alarms", out(quiet, "false_alarm"), len(quiet), GATE["false_alarm_rate"], "max")]


def report(results: dict, dev_types: set) -> str:
    rows = [r for r in results["cases"] if r.get("answers")]
    versions = [v for v in NAMES if all(v in r["answers"] for r in rows)]
    split, lines = results["split"], []
    lines.append(f"# {split.capitalize()} run: is the gap real, and is the gate failure certain?\n")
    lines.append(f"{len(rows)} cases, model `{results['model']}`. Generated by `python -m eval.compare --split {split} "
                 f"--model {results['model']}` from the logged results file. Scoring is code (`eval/score.py`); "
                 "no model judges a model.\n")

    lines.append("## The gate, with 95% intervals\n")
    lines.append("Wilson intervals. A criterion fails for sure only when its whole interval is on the wrong side of "
                 "the limit; otherwise this many cases can't tell a pass from a fail.\n")
    lines.append("| Version | " + " | ".join(f"{c} (limit {'≤' if s == 'max' else '≥'} {lim:.0%})"
                                             for c, _, _, lim, s in gate_rows(rows, versions[0])) + " |")
    lines.append("| --- | --- | --- | --- |")
    for v in versions:
        cells = [f"{_rate(k, n)}: {against_gate(k, n, lim, s)}" for _, k, n, lim, s in gate_rows(rows, v)]
        lines.append(f"| {NAMES[v]} | " + " | ".join(cells) + " |")

    if len(versions) < 2:
        return "\n".join(lines) + "\n"
    lines.append("\n## Paired comparison\n")
    need = wins_needed()
    lines.append("Same cases, same evidence pack. Only the cases where two versions disagree count, and the exact "
                 f"McNemar test asks whether that split could be chance. At p < 0.05 a version must win at least {need} "
                 "disagreements and lose none to show it is better.\n")
    lines.append("| Versions | Same outcome | Only the first right | Only the second right | Exact McNemar p | Verdict |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    pairs = [(a, b) for i, a in enumerate(versions) for b in versions[i + 1:]]
    for a, b in pairs:
        p = paired(rows, a, b)
        if p["p"] < 0.05:
            verdict = f"{NAMES[a] if len(p['a_only']) > len(p['b_only']) else NAMES[b]} is better"
        elif not p["a_only"] and not p["b_only"]:
            verdict = "identical on right answers"
        else:
            verdict = "no detectable difference"
        ids = lambda xs: f"{len(xs)}" + (f" ({', '.join(xs)})" if xs else "")  # noqa: E731
        lines.append(f"| {NAMES[a]} vs {NAMES[b]} | {p['same_outcome']}/{p['cases']} | {ids(p['a_only'])} | "
                     f"{ids(p['b_only'])} | {p['p']:.2f} | {verdict} |")

    if "baseline" in versions:
        ship = versions[-1]
        lines.append(f"\n## Where the misses are: {NAMES['baseline']} vs {NAMES[ship]}, by case type\n")
        lines.append("If a few hard cases decided the comparison, they would show up as cases only one version got "
                     "right.\n")
        lines.append("| Case type | Cases | Both right | Both not right | Only rules right | Only model right |")
        lines.append("| --- | --- | --- | --- | --- | --- |")
        for t in TYPES:
            rs = [r for r in rows if case_type(r, dev_types) == t]
            if not rs:
                continue
            p = paired(rs, "baseline", ship)
            lines.append(f"| {t} | {p['cases']} | {p['both_right']} | {p['both_not_right']} | "
                         f"{', '.join(p['a_only']) or 0} | {', '.join(p['b_only']) or 0} |")
    return "\n".join(lines) + "\n"


def dev_incident_types() -> set:
    bench = json.loads((ROOT / "data" / "benchmark.json").read_text(encoding="utf-8"))["cases"]
    return {(c.get("incident") or {}).get("type") for c in bench if c["split"] == "dev" and c.get("incident")}


def write(results_path: pathlib.Path) -> str:
    results = json.loads(results_path.read_text(encoding="utf-8"))
    text = report(results, dev_incident_types())
    (results_path.parent / f"{results_path.stem}_comparison.md").write_text(text, encoding="utf-8", newline="\n")
    return text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=["dev", "holdout"], required=True)
    ap.add_argument("--model", default="gemini-3.5-flash-lite")
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")
    print(write(ROOT / "eval" / "results" / f"{args.split}_{args.model}.json"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
